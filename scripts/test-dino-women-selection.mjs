import assert from 'node:assert/strict';
import { womenSelectionStatus } from '../lib/dino-coach/women-selection.ts';
const players = [{ id: 'w', women_eligible: true }, { id: 'm', men_eligible: true }, { id: 'both', women_eligible: true, men_eligible: true }, { id: 'unreviewed', women_eligible: null, men_eligible: null }, { id: 'other', women_eligible: false }];
const pick = (playerId, positionType = 'starter') => ({ playerId, positionType });
const status = ids => womenSelectionStatus(ids, players, true);
assert.equal(womenSelectionStatus([], players, false).valid, true);
assert.deepEqual(status([]).errors, ['All teams must include at least one player from the men’s and women’s sections in the squad']);
assert.equal(status([pick('w')]).valid, false, 'Women’s membership alone does not satisfy men’s section');
assert.equal(status([pick('m')]).valid, false, 'Men’s membership alone does not satisfy women’s section');
assert.equal(status([pick('w'),pick('w','bench')]).squadCount, 1);
assert.equal(status([pick('w','bench'),pick('m','bench')]).valid, true, 'Both representatives may be on the bench');
assert.equal(status([pick('w'),pick('m','bench')]).valid, true);
assert.equal(status([pick('w'),pick('m')]).valid, true);
assert.equal(status([pick('w'),pick('unreviewed'),pick('unknown'),pick('other')]).valid, false, 'Do not infer men’s membership from unknown or false women’s membership');
assert.equal(status([pick('both')]).valid, true, 'Explicit dual-section membership represents both sections');
assert.equal(womenSelectionStatus([pick('w'),pick('m')],players.map(p=>({...p,team_label:'NDCC',role:'BOWL'})),true).valid,true);
console.log('PASS section representation: missing either section, bench, duplicate IDs, unknown and dual membership, season controls');
