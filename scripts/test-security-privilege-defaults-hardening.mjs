#!/usr/bin/env node
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import {
  applyMigrations,
  createTestDatabase,
  dropTestDatabase,
  psql,
} from './lib/local-db.mjs';

const DB = 'ndcc_security_privilege_defaults';
const MIGRATION = '20260830130837_security_privilege_defaults_hardening.sql';

function bool(database, sql) {
  return psql(database, sql) === 't';
}

assert.equal(
  existsSync('app/api/admin/auth/bootstrap/route.ts'),
  false,
  'the retired HTTP bootstrap route must not be present',
);

const migration = readFileSync(`supabase/migrations/${MIGRATION}`, 'utf8');
assert.match(
  migration,
  /ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public/i,
  'the application migration owner must receive hardened defaults',
);

createTestDatabase(DB);
try {
  // Reproduce the relevant live Supabase defaults and legacy RPCs before the
  // forward migration is applied.
  psql(DB, `
    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
      GRANT ALL PRIVILEGES ON TABLES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
      GRANT ALL PRIVILEGES ON SEQUENCES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public
      GRANT EXECUTE ON FUNCTIONS TO PUBLIC, anon, authenticated, service_role;

    CREATE FUNCTION public.crypt(password text, salt text)
    RETURNS text LANGUAGE sql IMMUTABLE STRICT
    AS 'SELECT extensions.crypt(password, salt)';

    CREATE FUNCTION public.gen_salt(alg text)
    RETURNS text LANGUAGE sql STRICT
    AS 'SELECT extensions.gen_salt(alg)';

    CREATE FUNCTION public.gen_salt(alg text, rounds integer)
    RETURNS text LANGUAGE sql STRICT
    AS 'SELECT extensions.gen_salt(alg, rounds)';

    CREATE FUNCTION public.ndcc_bootstrap_first_admin(text, text, text)
    RETURNS uuid LANGUAGE sql SECURITY DEFINER
    AS 'SELECT NULL::uuid';

    CREATE TABLE public.intentional_public_read (id integer PRIMARY KEY);
    ALTER TABLE public.intentional_public_read ENABLE ROW LEVEL SECURITY;
    CREATE POLICY intentional_public_read_select
      ON public.intentional_public_read FOR SELECT TO anon, authenticated
      USING (true);
    REVOKE ALL PRIVILEGES ON TABLE public.intentional_public_read
      FROM PUBLIC, anon, authenticated;
    GRANT SELECT ON TABLE public.intentional_public_read TO anon, authenticated;
  `);

  applyMigrations(DB, [MIGRATION]);

  for (const signature of [
    'public.crypt(text,text)',
    'public.gen_salt(text)',
    'public.gen_salt(text,integer)',
    'public.ndcc_bootstrap_first_admin(text,text,text)',
  ]) {
    assert.equal(
      psql(DB, `SELECT to_regprocedure('${signature}') IS NULL`),
      't',
      `${signature} must be retired`,
    );
  }

  for (const role of ['anon', 'authenticated']) {
    assert.equal(
      bool(DB, `SELECT has_table_privilege('${role}', 'public.intentional_public_read', 'SELECT')`),
      true,
      `${role} must retain an existing intentional public read`,
    );
  }

  // Objects created after the migration inherit no browser privileges, while
  // service_role retains the server-side access needed by application routes.
  psql(DB, `
    CREATE TABLE public.future_table_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
    CREATE SEQUENCE public.future_sequence_probe;
    CREATE FUNCTION public.future_function_probe() RETURNS integer
      LANGUAGE sql AS 'SELECT 1';
  `);

  for (const role of ['anon', 'authenticated']) {
    for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER']) {
      assert.equal(
        bool(DB, `SELECT has_table_privilege('${role}', 'public.future_table_probe', '${privilege}')`),
        false,
        `${role} must not inherit ${privilege} on future tables`,
      );
    }
    for (const privilege of ['USAGE', 'SELECT', 'UPDATE']) {
      assert.equal(
        bool(DB, `SELECT has_sequence_privilege('${role}', 'public.future_sequence_probe', '${privilege}')`),
        false,
        `${role} must not inherit ${privilege} on future sequences`,
      );
    }
    assert.equal(
      bool(DB, `SELECT has_function_privilege('${role}', 'public.future_function_probe()', 'EXECUTE')`),
      false,
      `${role} must not inherit execution on future functions`,
    );
  }

  for (const privilege of ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER']) {
    assert.equal(
      bool(DB, `SELECT has_table_privilege('service_role', 'public.future_table_probe', '${privilege}')`),
      true,
      `service_role must retain ${privilege} on future tables`,
    );
  }
  for (const privilege of ['USAGE', 'SELECT', 'UPDATE']) {
    assert.equal(
      bool(DB, `SELECT has_sequence_privilege('service_role', 'public.future_sequence_probe', '${privilege}')`),
      true,
      `service_role must retain ${privilege} on future sequences`,
    );
  }
  assert.equal(
    bool(DB, "SELECT has_function_privilege('service_role', 'public.future_function_probe()', 'EXECUTE')"),
    true,
    'service_role must retain execution on future functions',
  );
} finally {
  dropTestDatabase(DB);
}

console.log('Security privilege-default hardening database checks passed.');
