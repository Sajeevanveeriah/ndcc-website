import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const scriptsDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptsDir, '..');
const tmpDir = join(scriptsDir, '.club-season-wizard-tmp');
rmSync(tmpDir, { recursive: true, force: true });
mkdirSync(tmpDir, { recursive: true });
writeFileSync(join(tmpDir, 'club-seasons.ts'), "export function slugifySeasonName(name: string) { return name.trim().toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }\n");
writeFileSync(join(tmpDir, 'club-season-wizard.ts'), readFileSync(join(repoRoot, 'lib/club-season-wizard.ts'), 'utf8').replace("from './club-seasons'", "from './club-seasons.ts'"));
const { WIZARD_STEPS, COPY_SECTIONS, validateSeasonWizardPayload, buildSeasonWizardPreview } = await import(pathToFileURL(join(tmpDir, 'club-season-wizard.ts')).href);
assert.equal(WIZARD_STEPS.length, 11);
assert.ok(COPY_SECTIONS.includes('teams'));
assert.deepEqual(validateSeasonWizardPayload({}), ['Season name is required.', 'Start date is required.', 'End date is required.']);
assert.match(validateSeasonWizardPayload({ name: '2027/2028 Season', startDate: '2027-10-01', endDate: '2027-03-31' }).join(' '), /End date/);
const preview = buildSeasonWizardPreview({ name: '2027/2028 Season', startDate: '2027-10-01', endDate: '2028-03-31', copySections: { teams: true, appointments: true }, registrationUrl: 'https://example.com/2026' }, new Date('2026-07-12T00:00:00Z'));
assert.equal(preview.slug, '2027-2028-season');
assert.equal(preview.selectedSections.length, 2);
assert.equal(preview.warnings.length, 1);
const migration = readFileSync(join(repoRoot, 'supabase/migrations/20260712110000_club_season_wizard.sql'), 'utf8');
assert.match(migration, /club_season_wizard_states/);
assert.match(migration, /activate_club_season/);
assert.match(migration, /club_seasons_one_current_idx|is_current = FALSE/);
const api = readFileSync(join(repoRoot, 'app/api/admin/club-seasons/wizard/route.ts'), 'utf8');
assert.match(api, /idempotencyKey/);
assert.match(api, /activate_club_season/);
rmSync(tmpDir, { recursive: true, force: true });
console.log('Club season wizard checks passed.');
